#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";

/** @typedef {{name: string, kind: string, entry: string, output: string, validate: (entryModule: WorkflowEntryModule, workflow: WorkflowBuild) => void}} WorkflowBuild */
/** @typedef {{
 *   workflowMeta: Record<string, unknown>,
 *   run: (...args: any[]) => any,
 *   materialKind: string,
 * }} WorkflowEntryModule */

const execFileAsync = promisify(execFile);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const WORKFLOW_SOURCE_ROOT = join(ROOT, "scripts", "workflows");
const WORKFLOWS = [
  {
    name: "paper",
    kind: "paper",
    validate: validateMaterialEntry,
  },
  {
    name: "book",
    kind: "book",
    validate: validateMaterialEntry,
  },
  {
    name: "talk",
    kind: "talk",
    validate: validateMaterialEntry,
  },
  {
    name: "webpage",
    kind: "webpage",
    validate: validateMaterialEntry,
  },
  {
    name: "translation",
    kind: "translation",
    validate: validateMaterialEntry,
  },
  {
    name: "author",
    kind: "author",
    validate: validateMaterialEntry,
  },
  {
    name: "topic",
    kind: "topic",
    validate: validateMaterialEntry,
  },
].map(({ name, ...config }) => ({
  name,
  entry: join(WORKFLOW_SOURCE_ROOT, `${name}.entry.mts`),
  output: join(ROOT, "workflows", `${name}.mjs`),
  ...config,
}));
const CLAUDE_WORKFLOW_MAX_BYTES = 512 * 1024;
const ARTIFACT_CONTRACT_ROOT = join(
  WORKFLOW_SOURCE_ROOT,
  "artifact-contracts",
);
const ARTIFACT_CONTRACT_MODULE = join(
  ARTIFACT_CONTRACT_ROOT,
  "generated.mjs",
);
const ARTIFACT_CONTRACT_TYPES = join(
  ARTIFACT_CONTRACT_ROOT,
  "generated.d.mts",
);
const CHECK = process.argv.slice(2).includes("--check");

const ARTIFACT_CONTRACTS = [
  { type: "author", exportName: "AUTHOR_ARTIFACT_CONTRACT" },
  { type: "paper", exportName: "PAPER_ARTIFACT_CONTRACT" },
  { type: "chapter", exportName: "CHAPTER_ARTIFACT_CONTRACT" },
  { type: "book", exportName: "BOOK_ARTIFACT_CONTRACT" },
  { type: "talk", exportName: "TALK_ARTIFACT_CONTRACT" },
  { type: "webpage", exportName: "WEBPAGE_ARTIFACT_CONTRACT" },
];

const generatedArtifactContractModule =
  await renderArtifactContractModule();
const generatedArtifactContractTypes =
  await renderArtifactContractDeclarations();
if (CHECK) {
  await assertCurrent(
    ARTIFACT_CONTRACT_MODULE,
    generatedArtifactContractModule,
    "artifact-contract module is stale; run npm run build:workflows",
  );
  await assertCurrent(
    ARTIFACT_CONTRACT_TYPES,
    generatedArtifactContractTypes,
    "artifact-contract declarations are stale; run npm run build:workflows",
  );
} else {
  await writeFile(
    ARTIFACT_CONTRACT_MODULE,
    generatedArtifactContractModule,
    "utf8",
  );
  await writeFile(
    ARTIFACT_CONTRACT_TYPES,
    generatedArtifactContractTypes,
    "utf8",
  );
}

for (const workflow of WORKFLOWS) await buildWorkflow(workflow);

/** @param {WorkflowBuild} workflow */
async function buildWorkflow(workflow) {
  const { name, entry, output } = workflow;
  const result = await build({
    absWorkingDir: ROOT,
    bundle: true,
    charset: "utf8",
    entryPoints: [entry],
    format: "iife",
    globalName: "__quasiWorkflow",
    legalComments: "none",
    logLevel: "silent",
    minifyWhitespace: true,
    platform: "neutral",
    sourcemap: false,
    target: ["es2022"],
    treeShaking: true,
    write: false,
  });
  if (result.outputFiles.length !== 1)
    throw new Error(
      `expected one ${name} workflow bundle, got ${result.outputFiles.length}`,
    );

  const bundledSource = result.outputFiles[0].text.trimEnd();
  const entryModule = new Function(
    `${bundledSource}\nreturn __quasiWorkflow;`,
  )();
  workflow.validate(entryModule, workflow);
  const { workflowMeta } = entryModule;

  const generated = `// GENERATED by scripts/build-workflows.mjs. DO NOT EDIT.
// Source of truth: scripts/workflows/${name}.entry.mts and its ESM imports.

export const meta = ${JSON.stringify(workflowMeta, null, 2)}

${bundledSource}

return await __quasiWorkflow.run({ agent, pipeline }, args)
`;

  await validateRuntimeBundle(generated);
  validateBundleSize(generated);
  if (CHECK) {
    await assertCurrent(
      output,
      generated,
      `${name} workflow bundle is stale; run npm run build:workflows`,
    );
    process.stdout.write(`${name} workflow bundle is current\n`);
  } else {
    await writeFile(output, generated, "utf8");
    process.stdout.write(`generated workflows/${name}.mjs\n`);
  }
}

/**
 * @param {WorkflowEntryModule} entryModule
 * @param {WorkflowBuild} workflow
 */
function validateMaterialEntry(entryModule, workflow) {
  validateEntryContract(entryModule, workflow.name);
  if (entryModule.materialKind !== workflow.kind)
    throw new Error(
      `${workflow.name} workflow source entry must export materialKind=${workflow.kind}`,
    );
}

/** @param {WorkflowEntryModule} entryModule @param {string} name */
function validateEntryContract(entryModule, name) {
  if (
    !entryModule.workflowMeta ||
    typeof entryModule.workflowMeta !== "object" ||
    Array.isArray(entryModule.workflowMeta)
  )
    throw new Error(`${name} workflow source entry must export workflowMeta`);
  if (typeof entryModule.run !== "function")
    throw new Error(`${name} workflow source entry must export run`);
}

/** @returns {Promise<string>} */
async function renderArtifactContractModule() {
  const python =
    process.env.PYTHON ||
    (process.env.VIRTUAL_ENV
      ? join(process.env.VIRTUAL_ENV, "bin", "python")
      : "python3");
  const exporter = join(
    ROOT,
    "scripts",
    "schemas",
    "export_contracts.py",
  );
  const { stdout } = await execFileAsync(
    python,
    [exporter, ...ARTIFACT_CONTRACTS.map((contract) => contract.type)],
    {
      cwd: ROOT,
      maxBuffer: 10 * 1024 * 1024,
    },
  );
  const contracts = JSON.parse(stdout);
  const { stdout: topicOutlineStdout } = await execFileAsync(
    python,
    [exporter, "--topic-outline"],
    {
      cwd: ROOT,
      maxBuffer: 10 * 1024 * 1024,
    },
  );
  const topicOutlineSubquestions = JSON.parse(topicOutlineStdout);
  const { stdout: operationsStdout } = await execFileAsync(
    python,
    [exporter, "--operations"],
    {
      cwd: ROOT,
      maxBuffer: 10 * 1024 * 1024,
    },
  );
  const operationCatalog = JSON.parse(operationsStdout);
  if (
    !operationCatalog ||
    typeof operationCatalog !== "object" ||
    Array.isArray(operationCatalog)
  )
    throw new Error("schema exporter omitted OPERATION_CATALOG");
  const declarations = ARTIFACT_CONTRACTS.map((contract) => {
    const value = contracts[contract.type];
    if (
      !value ||
      value.artifact_type !== contract.type ||
      typeof value.schema_version !== "string"
    )
      throw new Error(
        `artifact schema exporter omitted ${contract.type}`,
      );
    return `export const ${contract.exportName} = ${JSON.stringify(
      value,
      null,
      2,
    )};`;
  });
  declarations.push(
    `export const TOPIC_OUTLINE_SUBQUESTIONS_SCHEMA = ${JSON.stringify(
      topicOutlineSubquestions,
      null,
      2,
    )};`,
  );
  declarations.push(
    `export const OPERATION_CATALOG = ${JSON.stringify(
      operationCatalog,
      null,
      2,
    )};`,
  );
  return `// GENERATED by scripts/build-workflows.mjs. DO NOT EDIT.
// Source of truth: scripts/schemas/ frontmatter models, BodySchema, and operations.py.

${declarations.join("\n\n")}
`;
}

/** @returns {Promise<string>} */
async function renderArtifactContractDeclarations() {
  const python =
    process.env.PYTHON ||
    (process.env.VIRTUAL_ENV
      ? join(process.env.VIRTUAL_ENV, "bin", "python")
      : "python3");
  const exporter = join(
    ROOT,
    "scripts",
    "schemas",
    "export_contracts.py",
  );
  const { stdout } = await execFileAsync(
    python,
    [
      exporter,
      "--typescript",
      ...ARTIFACT_CONTRACTS.map((contract) => contract.type),
    ],
    {
      cwd: ROOT,
      maxBuffer: 10 * 1024 * 1024,
    },
  );
  if (!stdout.startsWith("// GENERATED by scripts/build-workflows.mjs. DO NOT EDIT."))
    throw new Error("artifact schema exporter omitted TypeScript declarations");
  return stdout;
}

/**
 * @param {string} path
 * @param {string} expected
 * @param {string} message
 */
async function assertCurrent(path, expected, message) {
  let current;
  try {
    current = await readFile(path, "utf8");
  } catch (error) {
    if (
      error instanceof Error &&
      "code" in error &&
      error.code === "ENOENT"
    )
      throw new Error(message);
    throw error;
  }
  if (current !== expected) throw new Error(message);
}

/** @param {string} source */
async function validateRuntimeBundle(source) {
  const metaExports = source.match(
    /^\s*export\s+const\s+meta\s*=/gm,
  );
  if (!metaExports || metaExports.length !== 1)
    throw new Error(
      "workflow bundle must contain exactly one export const meta",
    );

  const body = source.replace(
    /^\s*export\s+const\s+meta\s*=/m,
    "const meta =",
  );
  if (/^\s*import(?:\s|\{|\*)/m.test(body))
    throw new Error("workflow bundle must not contain static import");
  if (/\bimport\s*\(/.test(body))
    throw new Error("workflow bundle must not contain dynamic import");
  if (/\brequire\s*\(/.test(body))
    throw new Error("workflow bundle must not contain require()");
  if (/^\s*export\b/m.test(body))
    throw new Error("workflow bundle must not contain a second export");
  if (/from\s+["']node:fs|["']fs["']/.test(body))
    throw new Error("workflow bundle must not contain fs access");
  const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
  new AsyncFunction("agent", "pipeline", "args", body);
}

/** @param {string} source */
function validateBundleSize(source) {
  const bytes = Buffer.byteLength(source, "utf8");
  if (bytes > CLAUDE_WORKFLOW_MAX_BYTES)
    throw new Error(
      `workflow bundle is ${bytes} bytes; Claude Code accepts at most ${CLAUDE_WORKFLOW_MAX_BYTES}`,
    );
}
