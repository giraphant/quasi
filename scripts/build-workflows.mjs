#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";
import { STAGE_CHAINS } from "./workflows/operations/chains.mjs";
import { makeOperationContext } from "./workflows/run-stage-context.mjs";

const execFileAsync = promisify(execFile);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const WORKFLOW_SOURCE_ROOT = join(ROOT, "scripts", "workflows");
const WORKFLOWS = ["run-stage"].map((name) => ({
  name,
  entry: join(WORKFLOW_SOURCE_ROOT, `${name}.entry.mjs`),
  output: join(ROOT, "workflows", `${name}.mjs`),
}));
const CLAUDE_WORKFLOW_MAX_BYTES = 512 * 1024;
const ARTIFACT_CONTRACT_ROOT = join(
  WORKFLOW_SOURCE_ROOT,
  "artifact-contracts",
);
const ARTIFACT_CONTRACT_MODULE = join(
  ARTIFACT_CONTRACT_ROOT,
  "generated.mjs",
);
const CHECK = process.argv.slice(2).includes("--check");
const CHAIN_PROBE_CONTEXT_OVERRIDES = {};

const ARTIFACT_CONTRACTS = [
  { type: "author", exportName: "AUTHOR_ARTIFACT_CONTRACT" },
  { type: "paper", exportName: "PAPER_ARTIFACT_CONTRACT" },
  { type: "chapter", exportName: "CHAPTER_ARTIFACT_CONTRACT" },
  { type: "book", exportName: "BOOK_ARTIFACT_CONTRACT" },
  { type: "talk", exportName: "TALK_ARTIFACT_CONTRACT" },
];

const generatedArtifactContractModule =
  await renderArtifactContractModule();
if (CHECK) {
  await assertCurrent(
    ARTIFACT_CONTRACT_MODULE,
    generatedArtifactContractModule,
    "artifact-contract module is stale; run npm run build:workflows",
  );
} else {
  await writeFile(
    ARTIFACT_CONTRACT_MODULE,
    generatedArtifactContractModule,
    "utf8",
  );
}

for (const workflow of WORKFLOWS) await buildWorkflow(workflow);

async function buildWorkflow({ name, entry, output }) {
  const entryModule = await import(
    `${pathToFileURL(entry).href}?workflow-build=${name}`
  );
  const { workflowMeta } = entryModule;
  if (!workflowMeta || typeof workflowMeta !== "object")
    throw new Error(`${name} workflow source entry must export workflowMeta`);
  validateStageChainParity(entryModule);

  const result = await build({
    absWorkingDir: ROOT,
    bundle: true,
    charset: "utf8",
    entryPoints: [entry],
    format: "iife",
    globalName: "__quasiWorkflow",
    legalComments: "none",
    logLevel: "silent",
    minifyWhitespace: true,
    platform: "neutral",
    sourcemap: false,
    target: ["es2022"],
    treeShaking: true,
    write: false,
  });
  if (result.outputFiles.length !== 1)
    throw new Error(
      `expected one ${name} workflow bundle, got ${result.outputFiles.length}`,
    );

  const bundledSource = result.outputFiles[0].text.trimEnd();
  const generated = `// GENERATED by scripts/build-workflows.mjs. DO NOT EDIT.
// Source of truth: scripts/workflows/${name}.entry.mjs and its ESM imports.

export const meta = ${JSON.stringify(workflowMeta, null, 2)}

${bundledSource}

return await __quasiWorkflow.run({ agent, parallel, phase, log }, args)
`;

  validateRuntimeBundle(generated);
  validateBundleSize(generated);
  if (CHECK) {
    await assertCurrent(
      output,
      generated,
      `${name} workflow bundle is stale; run npm run build:workflows`,
    );
    process.stdout.write(`${name} workflow bundle is current\n`);
  } else {
    await writeFile(output, generated, "utf8");
    process.stdout.write(`generated workflows/${name}.mjs\n`);
  }
}

function validateStageChainParity({ RUN_STAGE_REGISTRY, resolveStage }) {
  for (const [kind, chain] of Object.entries(STAGE_CHAINS)) {
    const registeredStages = RUN_STAGE_REGISTRY?.[kind];
    if (!registeredStages)
      throw new Error(
        `stage chain parity: kind=${kind} is missing from RUN_STAGE_REGISTRY`,
      );

    for (const stage of chain.sequence) {
      if (!Object.hasOwn(registeredStages, stage))
        throw new Error(
          `stage chain parity: kind=${kind} stage=${stage} is not registered`,
        );
    }

    for (const carry of chain.carries) {
      if (!chain.sequence.includes(carry.from))
        throw new Error(
          `stage chain parity: kind=${kind} carry.from=${carry.from} is not in the sequence`,
        );
      const operation = registeredStages[carry.from];
      const resolved = resolveStage(kind, carry.from);
      if (!resolved)
        throw new Error(
          `stage chain parity: kind=${kind} stage=${carry.from} does not resolve`,
        );
      const rawContext = CHAIN_PROBE_CONTEXT_OVERRIDES[operation] || {};
      let schema;
      try {
        const context = makeOperationContext(
          kind,
          "probe",
          operation,
          rawContext,
        );
        schema = resolved.row.schema(context);
      } catch (error) {
        throw new Error(
          `stage chain parity: cannot build receipt schema for operation=${operation}: ${
            error instanceof Error ? error.message : String(error)
          }`,
        );
      }
      const required = Array.isArray(schema?.required) ? schema.required : [];
      for (const field of carry.reads) {
        if (!required.includes(field))
          throw new Error(
            `stage chain parity: carry ${kind}.${carry.from} reads non-required receipt field=${field}`,
          );
      }
    }
  }
}

async function renderArtifactContractModule() {
  const python =
    process.env.PYTHON ||
    (process.env.VIRTUAL_ENV
      ? join(process.env.VIRTUAL_ENV, "bin", "python")
      : "python3");
  const exporter = join(
    ROOT,
    "scripts",
    "schemas",
    "export_contracts.py",
  );
  const { stdout } = await execFileAsync(
    python,
    [exporter, ...ARTIFACT_CONTRACTS.map((contract) => contract.type)],
    {
      cwd: ROOT,
      maxBuffer: 10 * 1024 * 1024,
    },
  );
  const contracts = JSON.parse(stdout);
  const declarations = ARTIFACT_CONTRACTS.map((contract) => {
    const value = contracts[contract.type];
    if (
      !value ||
      value.artifact_type !== contract.type ||
      typeof value.schema_version !== "string"
    )
      throw new Error(
        `artifact schema exporter omitted ${contract.type}`,
      );
    return `export const ${contract.exportName} = ${JSON.stringify(
      value,
      null,
      2,
    )};`;
  });
  return `// GENERATED by scripts/build-workflows.mjs. DO NOT EDIT.
// Source of truth: scripts/schemas/ frontmatter models and BodySchema.

${declarations.join("\n\n")}
`;
}

async function assertCurrent(path, expected, message) {
  let current;
  try {
    current = await readFile(path, "utf8");
  } catch (error) {
    if (error && error.code === "ENOENT")
      throw new Error(message);
    throw error;
  }
  if (current !== expected) throw new Error(message);
}

function validateRuntimeBundle(source) {
  const metaExports = source.match(
    /^\s*export\s+const\s+meta\s*=/gm,
  );
  if (!metaExports || metaExports.length !== 1)
    throw new Error(
      "workflow bundle must contain exactly one export const meta",
    );

  const withoutMeta = source.replace(
    /^\s*export\s+const\s+meta\s*=/m,
    "const meta =",
  );
  if (/^\s*import(?:\s|\{|\*)/m.test(withoutMeta))
    throw new Error("workflow bundle must not contain static import");
  if (/^\s*export(?:\s|\{|\*)/m.test(withoutMeta))
    throw new Error(
      "workflow bundle must not contain exports after meta",
    );
  if (/\bimport\s*\(/.test(withoutMeta))
    throw new Error("workflow bundle must not contain dynamic import");
  if (/\brequire\s*\(/.test(withoutMeta))
    throw new Error("workflow bundle must not contain require()");
  if (/from\s+["']node:fs|["']fs["']/.test(withoutMeta))
    throw new Error("workflow bundle must not contain fs access");
  if (!/\breturn\s+await\s+__quasiWorkflow\.run\(/.test(source))
    throw new Error(
      "workflow bundle must return its result from the AsyncFunction body",
    );

  const AsyncFunction = Object.getPrototypeOf(
    async () => {},
  ).constructor;
  new AsyncFunction(
    "agent",
    "parallel",
    "phase",
    "log",
    "args",
    withoutMeta,
  );
}

function validateBundleSize(source) {
  const bytes = Buffer.byteLength(source, "utf8");
  if (bytes > CLAUDE_WORKFLOW_MAX_BYTES)
    throw new Error(
      `workflow bundle is ${bytes} bytes; Claude Code accepts at most ${CLAUDE_WORKFLOW_MAX_BYTES}`,
    );
}
